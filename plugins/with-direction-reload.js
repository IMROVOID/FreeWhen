/**
 * Expo config plugin: adds the `DirectionReload` native module to Android.
 *
 * ★ `/android/` IS GENERATED, SO A HAND-WRITTEN KOTLIN FILE DOES NOT SHIP.
 *
 * `.gitignore` ignores `/android/` wholesale, and `scripts/build/build-apk.sh`
 * runs `expo prebuild` before Gradle — so anything typed into
 * `android/app/src/main/java/...` exists only in the working copy that typed it.
 * A native module has to be re-created by the prebuild to reach CI and the APK.
 *
 * ★ WHAT THE MODULE IS FOR.
 *
 * React Native resolves a view's layout direction ONCE, when the hierarchy is
 * created: `I18nManager.forceRTL` only writes a `SharedPreferences` boolean that
 * nothing re-reads while a surface is alive (its own docs say "takes effect on
 * the next app reload"). `flexDirection: 'row'` is resolved by Android's layout
 * engine from the window's `layoutDirection`, so after switching to English every
 * string changed and every ROW kept its Persian order until the process was
 * killed. Recreating the Activity makes the window re-read the stored direction —
 * the same thing the OS does on a locale change, without the process restart.
 *
 * The JS side (`src/platform/direction-reload.native.ts`) calls it only when a
 * language switch actually flips the direction, and tolerates its absence.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Expo loads a config plugin through a bare Babel transform that does NOT strip
 * TypeScript-only syntax, so `import type` here is a hard parse error. The types
 * are imported as JSDoc instead — the file stays plain JavaScript.
 */
import { withDangerousMod, withMainApplication } from '@expo/config-plugins';

/** @typedef {import('@expo/config-plugins').ConfigPlugin} ConfigPlugin */

/** The Java package and directory the sources are written into. */
const PACKAGE = 'ir.freewhen.app';
const SOURCE_DIR = join('android', 'app', 'src', 'main', 'java', ...PACKAGE.split('.'));

const MODULE_KT = `package ${PACKAGE}

import android.app.Activity
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReactContextBaseJavaModule
import com.facebook.react.bridge.ReactMethod

/**
 * Rebuilds the Activity so a native layout-direction change takes effect.
 *
 * React Native resolves a view's layout direction once, when the hierarchy is
 * created, and I18nManager.forceRTL only writes a preference nothing re-reads
 * while a surface is alive. flexDirection: 'row' is therefore fixed for the
 * life of the window, which is why a language switch reflowed every string and no
 * row until the app was restarted.
 *
 * recreate() tears down and rebuilds the window, which re-reads the direction
 * and re-creates the hierarchy under it.
 *
 * Generated by plugins/with-direction-reload.js — do not edit in android/.
 */
class DirectionReloadModule(reactContext: ReactApplicationContext) :
    ReactContextBaseJavaModule(reactContext) {

  override fun getName(): String = "DirectionReload"

  @ReactMethod
  fun recreate() {
    val activity: Activity? = reactApplicationContext.currentActivity
    activity?.runOnUiThread {
      // The callback can land after the user has left the screen; a finished
      // Activity cannot be recreated and would throw.
      if (activity.isFinishing || activity.isDestroyed) return@runOnUiThread
      activity.recreate()
    }
  }
}
`;

const PACKAGE_KT = `package ${PACKAGE}

import com.facebook.react.ReactPackage
import com.facebook.react.bridge.NativeModule
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.uimanager.ViewManager

/**
 * Registers [DirectionReloadModule].
 *
 * Generated by plugins/with-direction-reload.js — do not edit in android/.
 */
class DirectionReloadPackage : ReactPackage {
  override fun createNativeModules(reactContext: ReactApplicationContext): List<NativeModule> =
      listOf(DirectionReloadModule(reactContext))

  override fun createViewManagers(
      reactContext: ReactApplicationContext
  ): List<ViewManager<*, *>> = emptyList()
}
`;

/** Writes the two Kotlin sources into the generated Android project. */
/** @type {ConfigPlugin} */
const withDirectionReloadSources = (config) =>
  withDangerousMod(config, [
    'android',
    async (modConfig) => {
      const dir = join(modConfig.modRequest.projectRoot, SOURCE_DIR);
      mkdirSync(dir, { recursive: true });

      writeFileSync(join(dir, 'DirectionReloadModule.kt'), MODULE_KT, 'utf8');
      writeFileSync(join(dir, 'DirectionReloadPackage.kt'), PACKAGE_KT, 'utf8');

      return modConfig;
    },
  ]);

/**
 * Registers the package with the React host.
 *
 * The generated `MainApplication.kt` carries a `PackageList(this).packages.apply
 * { … }` block whose body is the documented place for a package, so the line is
 * inserted there. Anchoring on that call is what keeps this idempotent and what
 * fails loudly if the generated template changes shape.
 */
/** @type {ConfigPlugin} */
const withDirectionReloadPackage = (config) =>
  withMainApplication(config, (modConfig) => {
    const contents = modConfig.modResults.contents;

    if (contents.includes('DirectionReloadPackage()')) return modConfig;

    const anchor = /(PackageList\(this\)\.packages\.apply\s*\{)/;
    if (!anchor.test(contents)) {
      throw new Error(
        'with-direction-reload: the generated MainApplication has no ' +
          '`PackageList(this).packages.apply {` block to register the package in.',
      );
    }

    modConfig.modResults.contents = contents.replace(
      anchor,
      '$1\n          add(DirectionReloadPackage())',
    );

    return modConfig;
  });

/** @type {ConfigPlugin} */
const withDirectionReload = (config) =>
  withDirectionReloadPackage(withDirectionReloadSources(config));

export default withDirectionReload;

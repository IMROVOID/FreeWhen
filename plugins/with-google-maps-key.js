/**
 * Expo config plugin: declares the Google Maps API key the Android map needs.
 *
 * ★ THE DEFECT THIS FIXES: OPENING ANY MAP SCREEN KILLED THE APP.
 *
 * `react-native-maps` on Android has exactly one renderer — the Google Maps SDK.
 * `MapViewManager.setGoogleRenderer` calls `MapsInitializer.initialize(...)` the
 * moment the first `MapView` is created, before `mapType` is consulted. Without a
 * key in the manifest, that throws inside native view creation:
 *
 *   java.lang.RuntimeException: API key not found. Check that
 *     <meta-data android:name="com.google.android.geo.API_KEY"
 *                android:value="your API key"/>
 *     is in the <application> element of AndroidManifest.xml
 *     at com.rnmaps.fabric.MapViewManager.setGoogleRenderer
 *
 * ★ `mapType="none"` DOES NOT OPT OUT OF GOOGLE.
 *
 * Plan 64 chose `mapType="none"` over MapBox tiles so that the Google basemap would
 * not be drawn. That succeeds visually — every visible pixel is MapBox's — but the
 * SDK is still initialised, because the view object IS a Google map. Android's
 * Google Maps SDK has no keyless mode, so a key is mandatory even though the key
 * never authorises a pixel the user sees.
 *
 * ★ THE KEY COMES FROM THE ENVIRONMENT, NOT FROM THE CONFIG.
 *
 * A committed key would be a credential in the source tree, and `android/` is
 * regenerated by `prebuild`, so the manifest entry has to be written at build time.
 * The variable mirrors the MapBox token's handling: `EXPO_PUBLIC_*` for the values
 * the client inlines, `GOOGLE_MAPS_API_KEY` for this one, which is only ever read
 * while generating the manifest and never enters JS.
 *
 * ★ MISSING KEY IS A BUILD FAILURE, NOT A RUNTIME CRASH.
 *
 * Expo's own `android.config.googleMaps.apiKey` field accepts a placeholder happily,
 * and the failure then appears as a crash on a user's phone — which is exactly how
 * this defect reached a draft release. Requiring the variable during `prebuild`
 * moves the failure to the build log, where it costs nothing.
 *
 * The build script may pass an explicit placeholder for a local verification build
 * (`ALLOW_PLACEHOLDER_MAPS_KEY=1`); CI and release builds never set it.
 */

import { withAndroidManifest } from '@expo/config-plugins';

/** @typedef {import('@expo/config-plugins').ConfigPlugin} ConfigPlugin */

/** The meta-data name the Google Maps SDK looks for. */
const META_DATA_NAME = 'com.google.android.geo.API_KEY';

/**
 * Adds `<meta-data android:name="com.google.android.geo.API_KEY" ...>`.
 *
 * @type {ConfigPlugin}
 */
function withGoogleMapsKey(config) {
  // `globalThis.process` rather than a bare `process`: this file is linted with the
  // repo's browser-oriented globals, and the environment is only present while
  // `prebuild` runs under Node.
  const env = (globalThis.process && globalThis.process.env) || {};
  const fromEnv = String(env.GOOGLE_MAPS_API_KEY || '').trim();
  const allowPlaceholder = env.ALLOW_PLACEHOLDER_MAPS_KEY === '1';

  return withAndroidManifest(config, (config) => {
    const manifest = config.modResults?.manifest;
    if (!manifest) return config;

    /**
     * The placeholder is a BUILD-TIME marker, never a shipped value, and it is only
     * honoured when the caller explicitly asks for it. A release build without the
     * real variable fails here rather than crashing on a phone.
     */
    if (fromEnv === '' && !allowPlaceholder) {
      throw new Error(
        'GOOGLE_MAPS_API_KEY is not set. react-native-maps initialises the Google ' +
          'Maps SDK on Android even with mapType="none", and without this key the ' +
          'app crashes the moment a map screen opens. Set it in the build ' +
          'environment (see .env.example), or set ALLOW_PLACEHOLDER_MAPS_KEY=1 for ' +
          'a local verification build that will not be distributed.',
      );
    }

    const value = fromEnv === '' ? 'placeholder-for-verification-build' : fromEnv;

    manifest.$ = manifest.$ ?? {};
    if (!manifest.$['xmlns:tools']) {
      manifest.$['xmlns:tools'] = 'http://schemas.android.com/tools';
    }

    const application = manifest.application?.[0];
    if (!application) return config;

    const entries = Array.isArray(application['meta-data'])
      ? application['meta-data']
      : [];

    // Replace rather than duplicate: two entries make the SDK's choice undefined.
    const others = entries.filter((entry) => entry?.$?.['android:name'] !== META_DATA_NAME);

    application['meta-data'] = [
      ...others,
      { $: { 'android:name': META_DATA_NAME, 'android:value': value } },
    ];

    return config;
  });
}

export default withGoogleMapsKey;

/**
 * The app must not pull in a WorkManager that crashes the process at startup.
 *
 * ★ THE DEFECT THIS REPRODUCES: INSTANT CRASH AFTER THE SPLASH SCREEN.
 *
 * `react-native-maps` declares `androidx.work:work-runtime` (its Gradle line 104,
 * for the location-tracking path). That artifact registers
 * `androidx.work.impl.WorkDatabase` through `androidx.startup.InitializationProvider`,
 * and on this app's merged manifest the provider fails to instantiate. Because the
 * failure happens in a ContentProvider's `onCreate` — before `MainActivity`, before
 * React starts, before any JavaScript — the process dies at launch. There is no
 * JS-level error boundary that can catch it.
 *
 * Measured on an Android 15 emulator (SDK 35, x86_64):
 *
 *   v0.1.3 (before react-native-maps)  -> launches, process alive
 *   v0.1.4 (with react-native-maps)    -> FATAL EXCEPTION: main
 *       java.lang.RuntimeException: Unable to get provider
 *         androidx.startup.InitializationProvider
 *       Caused by: Failed to create an instance of class
 *         androidx.work.impl.WorkDatabase
 *       at androidx.work.WorkManagerInitializer
 *       at android.app.ActivityThread.installProvider
 *
 * ★ WHY A TEST RATHER THAN A MANUAL CHECK.
 *
 * A dependency that is never imported can still be merged into the APK's manifest
 * and crash the app, and nothing in `src/`, no typecheck and no unit test can see
 * it. The only place this defect is visible before a device is the native Android
 * configuration, so it is asserted there.
 *
 * The rule is not "never use WorkManager" — it is "the app must state explicitly
 * whether it initialises it", so a dependency bump cannot silently reintroduce a
 * startup provider the app does not own.
 */

import assert from 'node:assert/strict';
import { test } from 'node:test';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

function text(path: string): string {
  return readFileSync(path, 'utf8');
}

/** The app config, which `expo prebuild` turns into the Android manifest. */
const APP_JSON = 'app.json';

/**
 * Where an `expo` project declares Android-specific plugins and manifest
 * behaviour. `expo prebuild` regenerates `android/` from `app.json` on every
 * build, so a committed edit under `android/` does not survive — any manifest
 * fix has to live in the config.
 */
function androidConfig(): Record<string, unknown> {
  const config = JSON.parse(text(APP_JSON)) as {
    expo?: { android?: Record<string, unknown>; plugins?: unknown };
  };
  return { ...(config.expo ?? {}) };
}

/**
 * Everything that can change the merged Android manifest.
 *
 * ★ THE FIX LIVES IN A PLUGIN, NOT IN `android/`, SO THE TEST MUST READ THE PLUGIN.
 *
 * `android/` is regenerated by `prebuild` on every build (see
 * `plugins/with-direction-reload.js` for the same trap), so a manifest fix has to
 * be a config plugin. Asserting on `app.json` alone would miss it entirely — which
 * is exactly what happened on the first attempt at this test: the fix was
 * registered and the test still failed.
 */
function buildConfig(): string {
  const parts = [text(APP_JSON), text('package.json')];

  // Every registered plugin's source, since any of them may edit the manifest.
  const config = JSON.parse(text(APP_JSON)) as { expo?: { plugins?: unknown[] } };
  for (const entry of config.expo?.plugins ?? []) {
    const name = Array.isArray(entry) ? entry[0] : entry;
    if (typeof name !== 'string' || !name.startsWith('./plugins/')) continue;
    const path = name.replace(/^\.\//, '');
    if (existsSync(path)) parts.push(text(path));
  }

  // The Gradle file `prebuild` generates, when it is present.
  const gradle = join('android', 'app', 'build.gradle');
  if (existsSync(gradle)) parts.push(text(gradle));

  return parts.join('\n');
}

/* ── The regression ───────────────────────────────────────────────────────── */

test('react-native-maps still declares WorkManager, so the app must handle it', () => {
  // Arrange — the dependency that started this. If a future version stops
  // pulling WorkManager in, this assertion fails and the mitigation below can be
  // reconsidered rather than left in place forever.
  const gradle = 'node_modules/react-native-maps/android/build.gradle';

  if (!existsSync(gradle)) {
    // `node_modules` is absent in a bare checkout; the assertion below still
    // guards the config, so skip rather than fail for the wrong reason.
    return;
  }

  // Act
  const declares = /androidx\.work:work-runtime/.test(text(gradle));

  // Assert
  assert.equal(
    declares,
    true,
    'react-native-maps no longer declares androidx.work — re-check whether the WorkManager mitigation is still needed',
  );
});

test('the app explicitly controls androidx.startup initialisation', () => {
  // Arrange — the crash is `InitializationProvider` failing to create
  // `WorkDatabase`. Expo exposes manifest overrides through the android config,
  // which is what survives `prebuild`.
  const android = androidConfig().android as
    | { blockedPermissions?: string[]; manifestQueries?: unknown }
    | undefined;

  // Act — the app must DECLARE a position on the startup provider, either by
  // removing the entries or by providing the work-runtime initializer it needs.
  const config = buildConfig();

  // Assert — a WorkManager initializer that the app does not configure is the
  // defect; the app must name `work-runtime` somewhere in its own build config,
  // or exclude the provider explicitly.
  const handlesWorkManager =
    /androidx\.startup|work-runtime|WorkManagerInitializer|tools:node="remove"/.test(config);
  const hasAndroidSection = android !== undefined;

  assert.ok(hasAndroidSection, 'app.json has no expo.android section to carry the fix');
  assert.ok(
    handlesWorkManager,
    'the app pulls androidx.work in transitively but never configures or excludes its startup provider, so InitializationProvider crashes the process at launch',
  );
});

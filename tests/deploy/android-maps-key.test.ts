/**
 * Opening any screen with a map must not crash the app.
 *
 * ★ THE DEFECT THIS REPRODUCES: THE APP DIED ON THE FIRST MAP SCREEN.
 *
 * Entering an event crashed the process. The stack trace named the cause exactly:
 *
 *   java.lang.RuntimeException: API key not found. Check that
 *     <meta-data android:name="com.google.android.geo.API_KEY"
 *                android:value="your API key"/>
 *     is in the <application> element of AndroidManifest.xml
 *     at com.google.maps.api.android.lib6.drd.p.a
 *     at com.google.android.gms.maps.internal.CreatorImpl.logInitialization
 *     at com.rnmaps.fabric.MapViewManager.setGoogleRenderer
 *     at com.rnmaps.fabric.MapViewManager.optionsForInitialProps
 *     at com.rnmaps.fabric.MapViewManager.createViewInstance
 *
 * ★ `mapType="none"` DOES NOT AVOID GOOGLE MAPS — IT ONLY HIDES IT.
 *
 * The native surface uses `react-native-maps` with `mapType="none"` over MapBox
 * raster tiles, on the theory (Plan 64 D64-1) that a blank Google shell would host
 * our own tiles without needing Google. That reasoning was wrong at the native
 * layer: `MapViewManager.setGoogleRenderer` calls `MapsInitializer.initialize(...)`
 * unconditionally when the first `MapView` is created, before any `mapType` is
 * consulted. `react-native-maps` on Android has exactly one renderer — the Google
 * Maps SDK — so merely MOUNTING a map demands a Google API key.
 *
 * Android's Google Maps SDK has no public "tiles only, no key" mode. The library is
 * not misbehaving; our configuration is incomplete. The app therefore has to ship a
 * real `com.google.android.geo.API_KEY`, or it cannot render a map at all.
 *
 * ★ WHY THIS IS A MANIFEST ASSERTION AND NOT A UNIT TEST.
 *
 * The crash happens inside native view creation, in a `ContentProvider`-adjacent
 * path, long before any JavaScript. Nothing under `src/` can observe it, and
 * `mapType="none"` in the component reads as though Google is not involved — which
 * is precisely how the gap survived review.
 */

import assert from 'node:assert/strict';
import { test } from 'node:test';
import { existsSync, readFileSync } from 'node:fs';

const APP_JSON = 'app.json';

type ExpoConfig = {
  expo?: {
    android?: { config?: { googleMaps?: { apiKey?: string } } };
    plugins?: unknown[];
  };
};

function config(): ExpoConfig {
  return JSON.parse(readFileSync(APP_JSON, 'utf8')) as ExpoConfig;
}

/** Every plugin's source, since any of them may edit the manifest. */
function pluginSource(): string {
  const parts: string[] = [];
  for (const entry of config().expo?.plugins ?? []) {
    const name = Array.isArray(entry) ? entry[0] : entry;
    if (typeof name !== 'string' || !name.startsWith('./plugins/')) continue;
    const path = name.replace(/^\.\//, '');
    if (existsSync(path)) parts.push(readFileSync(path, 'utf8'));
  }
  return parts.join('\n');
}

/**
 * Whether the APK would declare the Google Maps key.
 *
 * Two legitimate routes, both checked: Expo's own `android.config.googleMaps.apiKey`
 * field, or a config plugin that writes the `<meta-data>` entry itself.
 */
function declaresGoogleMapsKey(): boolean {
  const fromExpo = config().expo?.android?.config?.googleMaps?.apiKey;
  if (typeof fromExpo === 'string' && fromExpo.trim() !== '') return true;

  return /com\.google\.android\.geo\.API_KEY/.test(pluginSource());
}

/* ── The regression ───────────────────────────────────────────────────────── */

test('the app declares a Google Maps API key, without which any map screen crashes', () => {
  // Arrange — `react-native-maps` is the Android map renderer, and mounting its
  // `MapView` initialises the Google SDK unconditionally.
  const usesReactNativeMaps = /react-native-maps/.test(readFileSync('package.json', 'utf8'));

  // Act
  const declared = declaresGoogleMapsKey();

  // Assert
  assert.equal(usesReactNativeMaps, true, 'react-native-maps is no longer a dependency');
  assert.equal(
    declared,
    true,
    'no com.google.android.geo.API_KEY is declared, so MapViewManager.setGoogleRenderer throws "API key not found" and the process dies the moment a map mounts',
  );
});

test('the key is supplied from configuration, not hardcoded in the manifest', () => {
  // ★ `android/` IS GITIGNORED AND REGENERATED BY `prebuild`, so a hand-edited
  // AndroidManifest.xml does not reach a build. A literal key committed to the
  // config would also be a credential in the source tree; the meta-data entry must
  // be written by the build, from the environment.
  const source = `${readFileSync(APP_JSON, 'utf8')}\n${pluginSource()}`;

  // Act — a 30+ character key value pasted next to the meta-data name.
  const hardcoded = /com\.google\.android\.geo\.API_KEY[\s\S]{0,200}?AIza[0-9A-Za-z_-]{30,}/.test(
    source,
  );

  // Assert
  assert.equal(hardcoded, false, 'a Google Maps API key is hardcoded in the app config');
});

test('the native surface no longer needs a Google key at all', () => {
  // ★ THE KEY WAS A WORKAROUND FOR A RENDERER THAT COULD NEVER WORK.
  //
  // `react-native-maps` initialised the Google SDK on every MapView AND attached
  // MapBox tiles as a `GoogleMap.TileOverlay`, so without a key the app crashed and
  // with one the map was still Google's. The native renderer is now a WebView
  // running the same `mapbox-gl` document as the browser, so the APK imports no
  // Google Maps SDK and the key is no longer required to render a map.
  const native = readFileSync('src/components/ui/InteractiveMap.native.tsx', 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '');

  assert.doesNotMatch(native, /react-native-maps/, 'the Google-hosted renderer is still imported');
  assert.match(native, /react-native-webview/, 'the native surface is not a WebView');
  assert.match(native, /mapbox-gl/, 'the document does not load MapBox');
});

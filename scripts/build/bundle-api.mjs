/**
 * Bundles the API into a single Vercel function.
 *
 * ★ WHY A BUNDLE AND NOT `api/index.ts` + THE WHOLE SERVER TREE.
 *
 * Vercel installs a function's dependencies from a `package.json` inside the
 * function directory. Shipping `server/` and asking it to resolve `pg` at
 * runtime means the deployment carries a node_modules graph the build step never
 * saw, and the first request pays for a resolution failure instead of a query.
 *
 * esbuild emits one file with `pg` left external (it has native optional
 * bindings Vercel must install), which is exactly the shape a Vercel function
 * wants.
 *
 * ★ `server/runtime/web-fetch.ts` IS THE ENTRY, UNCHANGED.
 *
 * It already implements `default (request: Request) => Promise<Response>`,
 * which is Vercel's convention. Nothing host-specific is added here.
 */
import { build } from 'esbuild';
import { mkdirSync } from 'node:fs';

mkdirSync('api', { recursive: true });

await build({
  entryPoints: ['server/runtime/web-fetch.ts'],
  outfile: 'api/index.js',
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  // `pg` stays external: it ships optional native bindings that must be
  // installed by the platform rather than inlined by the bundler.
  external: ['pg', 'pg-native'],
  // A single-file function registers itself as the default export.
  banner: { js: '// Generated by scripts/build/bundle-api.mjs — do not edit.' },
  logLevel: 'info',
});

console.log('api/index.js written');

